import '../../core/constants.dart';
import '../../core/utils/formatters.dart';
import '../models/booking.dart';

/// Format-neutral table that all exporters (XLSX / ODS / PDF) consume.
class ReportTable {
  const ReportTable({
    required this.title,
    required this.headers,
    required this.rows,
    required this.meta,
  });

  final String title;
  final List<String> headers;

  /// Cells are String or num (num stays numeric in spreadsheets).
  final List<List<Object?>> rows;
  final Map<String, String> meta;
}

class ReportBuilder {
  static String _dt(dynamic v) =>
      v == null ? '' : fmtDateTime(DateTime.tryParse('$v'));

  static ReportTable bookingRegister(
    List<Map<String, dynamic>> data, {
    required Map<String, String> filters,
    required String generatedBy,
  }) {
    final rows = data.map<List<Object?>>((r) {
      final sub = '${r['visitor_sub_category'] ?? ''}';
      final cat = '${r['visitor_category'] ?? ''}${sub.isEmpty ? '' : '($sub)'}';
      return [
        r['reference'] ?? '',
        r['visitor_name'] ?? '',
        r['organization'] ?? '',
        cat,
        roomTypes[r['room_type']] ?? '${r['room_type'] ?? ''}',
        r['num_rooms'] ?? 0,
        r['persons_lodging'] ?? 0,
        _dt(r['arrival_at']),
        _dt(r['departure_at']),
        RequestStatus.label('${r['status'] ?? ''}'),
        r['allotted_room_no'] ?? '',
        r['amount'] is num ? r['amount'] : null,
        r['payment_status'] == null ? '' : humanize('${r['payment_status']}'),
      ];
    }).toList();
    return ReportTable(
      title: 'EDC Booking Register',
      headers: const [
        'Booking ref',
        'Visitor',
        'Organisation',
        'Category',
        'Room type',
        'Rooms',
        'Persons',
        'Arrival',
        'Departure',
        'Status',
        'Room no.',
        'Amount (Rs.)',
        'Payment (simulated)',
      ],
      rows: rows,
      meta: {
        'Report date': fmtDateTime(DateTime.now()),
        'Generated by': generatedBy,
        ...filters,
        'Records': '${rows.length}',
        'Note':
            'Amount = receipt total where issued, otherwise estimate. Payments are prototype simulations.',
      },
    );
  }

  static ReportTable approvalReport(
    List<Map<String, dynamic>> data, {
    required Map<String, String> filters,
    required String generatedBy,
  }) {
    final rows = data
        .map<List<Object?>>((r) => [
              r['reference'] ?? '',
              r['visitor_name'] ?? '',
              roomTypes[r['room_type']] ?? '${r['room_type'] ?? ''}',
              r['stage_order'] ?? '',
              r['stage_name'] ?? '',
              r['authority_label'] ?? '',
              humanize('${r['step_status'] ?? ''}'),
              r['decided_by'] ?? '',
              _dt(r['decided_at']),
              r['reason'] ?? '',
            ])
        .toList();
    return ReportTable(
      title: 'EDC Approval & Rejection History',
      headers: const [
        'Booking ref',
        'Visitor',
        'Room type',
        'Stage',
        'Stage name',
        'Authority',
        'Decision',
        'Decided by',
        'Decided on',
        'Reason',
      ],
      rows: rows,
      meta: {
        'Report date': fmtDateTime(DateTime.now()),
        'Generated by': generatedBy,
        ...filters,
        'Records': '${rows.length}',
      },
    );
  }
}
